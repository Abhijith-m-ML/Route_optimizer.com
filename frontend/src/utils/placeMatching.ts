/**
 * Place Matching & Duplicate Prevention Utilities
 * 
 * Provides robust identification and deduplication of stops/destinations
 * within trip collections. Uses provider place IDs, coordinate proximity thresholds,
 * and normalized name heuristics to avoid false positives and false negatives.
 */

export interface PlaceLike {
  id?: string;
  placeId?: string;
  name?: string;
  originalName?: string;
  customName?: string;
  address?: string;
  shortAddress?: string;
  city?: string;
  state?: string;
  country?: string;
  coordinates?: {
    lat: number;
    lng: number;
  };
  stopOrder?: number;
  [key: string]: any;
}

/**
 * Normalizes a place identifier string by stripping common prefixes.
 */
export function normalizePlaceId(id?: string | null): string {
  if (!id || typeof id !== 'string') return '';
  return id.trim().replace(/^places\//, '').replace(/^place_/, '');
}

/**
 * Normalizes a place name for robust matching (lowercased, stripped of punctuation,
 * common suffixes like '(C)', extra whitespace).
 */
export function normalizePlaceName(name?: string | null): string {
  if (!name || typeof name !== 'string') return '';
  return name
    .toLowerCase()
    .replace(/\s*\(c\)\s*$/i, '')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Checks if two place names are compatible (identical, substring of each other,
 * or share significant tokens of >= 3 characters).
 */
export function namesAreCompatible(nameA?: string | null, nameB?: string | null): boolean {
  const normA = normalizePlaceName(nameA);
  const normB = normalizePlaceName(nameB);

  if (!normA || !normB) return false;
  if (normA === normB) return true;
  if (normA.includes(normB) || normB.includes(normA)) return true;

  const tokensA = normA.split(' ').filter((t) => t.length >= 3);
  const tokensB = normB.split(' ').filter((t) => t.length >= 3);

  // If they share at least one significant keyword (e.g., 'maradu')
  return tokensA.some((t) => tokensB.includes(t));
}

/**
 * Determines whether two place objects represent the exact same real-world place.
 * 
 * Evaluation Order:
 * 1. Non-empty normalized Place IDs match (Google Place ID or OSM ID)
 * 2. Stable Non-ephemeral IDs match
 * 3. Proximity coordinates check:
 *    - Within ~500m (0.005 deg) with compatible place names
 *    - Within ~15m (0.00015 deg) if names are not in direct conflict
 */
export function isSamePlace(a?: PlaceLike | null, b?: PlaceLike | null): boolean {
  if (!a || !b) return false;

  // 1. Direct placeId match (Google Place ID or OSM ID)
  const normPlaceIdA = normalizePlaceId(a.placeId);
  const normPlaceIdB = normalizePlaceId(b.placeId);
  if (normPlaceIdA && normPlaceIdB && normPlaceIdA === normPlaceIdB) {
    return true;
  }

  // 2. Direct ID match if not an autogenerated ephemeral stop ID
  if (a.id && b.id && a.id === b.id) {
    if (!a.id.startsWith('stop_') && !b.id.startsWith('stop_')) {
      return true;
    }
  }

  // 3. Fallback: Normalized coordinates and name matching
  if (a.coordinates && b.coordinates) {
    const latA = Number(a.coordinates.lat);
    const lngA = Number(a.coordinates.lng);
    const latB = Number(b.coordinates.lat);
    const lngB = Number(b.coordinates.lng);

    if (!isNaN(latA) && !isNaN(lngA) && !isNaN(latB) && !isNaN(lngB)) {
      const latDiff = Math.abs(latA - latB);
      const lngDiff = Math.abs(lngA - lngB);

      const nameA = a.originalName || a.customName || a.name;
      const nameB = b.originalName || b.customName || b.name;

      // If coordinates are in close proximity (< ~500m / 0.005 deg) and names are compatible
      if (latDiff <= 0.005 && lngDiff <= 0.005) {
        if (namesAreCompatible(nameA, nameB)) {
          return true;
        }
      }

      // If coordinates are virtually identical (< ~15m / 0.00015 deg)
      if (latDiff < 0.00015 && lngDiff < 0.00015) {
        // If neither has name, or names are compatible
        if (!nameA || !nameB || namesAreCompatible(nameA, nameB)) {
          return true;
        }
      }
    }
  }

  return false;
}

/**
 * Checks if a candidate place already exists in a collection of stops.
 * Returns the matching existing stop if found, or undefined if no duplicate exists.
 */
export function findDuplicateStop<T extends PlaceLike>(
  existingStops: T[] | undefined | null,
  candidate?: PlaceLike | null
): T | undefined {
  if (!Array.isArray(existingStops) || existingStops.length === 0 || !candidate) {
    return undefined;
  }
  return existingStops.find((stop) => isSamePlace(stop, candidate));
}

/**
 * Convenience boolean helper for checking if a candidate place is already in a stop list.
 */
export function hasDuplicateStop(
  existingStops: PlaceLike[] | undefined | null,
  candidate?: PlaceLike | null
): boolean {
  return Boolean(findDuplicateStop(existingStops, candidate));
}

/**
 * Deduplicates an array of stops within the same collection.
 * Preserves the order of first occurrence and reassigns 1-based stopOrder.
 */
export function deduplicateStops<T extends PlaceLike>(stops?: T[] | null): T[] {
  if (!Array.isArray(stops)) return [];
  const uniqueStops: T[] = [];

  for (const stop of stops) {
    const isDupe = uniqueStops.some((existing) => isSamePlace(existing, stop));
    if (!isDupe) {
      uniqueStops.push(stop);
    }
  }

  return uniqueStops.map((stop, idx) => ({
    ...stop,
    stopOrder: idx + 1,
  }));
}
